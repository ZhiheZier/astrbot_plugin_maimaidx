@overload
def computeRa(ds: float, achievement: float, *, israte: bool = False) -> Tuple[int, str]:
    """
    计算底分和评价
    
    Params:
        `ds`: 定数
        `achievement`: 成绩
        `israte`: 是否返回所有数据
    Returns:
        (底分, 评价)
    """
def computeRa(
    ds: float, 
    achievement: float, 
    *, 
    onlyrate: bool = False, 
    israte: bool = False
) -> Union[int, Tuple[int, str]]:
    if achievement < 50:
        baseRa = 7.0
        rate = 'D'
    elif achievement < 60:
        baseRa = 8.0
        rate = 'C'
    elif achievement < 70:
        baseRa = 9.6
        rate = 'B'
    elif achievement < 75:
        baseRa = 11.2
        rate = 'BB'
    elif achievement < 80:
        baseRa = 12.0
        rate = 'BBB'
    elif achievement < 90:
        baseRa = 13.6
        rate = 'A'
    elif achievement < 94:
        baseRa = 15.2
        rate = 'AA'
    elif achievement < 97:
        baseRa = 16.8
        rate = 'AAA'
    elif achievement < 98:
        baseRa = 20.0
        rate = 'S'
    elif achievement < 99:
        baseRa = 20.3
        rate = 'Sp'
    elif achievement < 99.5:
        baseRa = 20.8
        rate = 'SS'
    elif achievement < 100:
        baseRa = 21.1
        rate = 'SSp'
    elif achievement < 100.5:
        baseRa = 21.6
        rate = 'SSS'
    else:
        baseRa = 22.4
        rate = 'SSSp'

    if israte:
        data = (math.floor(ds * (min(100.5, achievement) / 100) * baseRa), rate)
    elif onlyrate:
        data = rate
    else:
        data = math.floor(ds * (min(100.5, achievement) / 100) * baseRa)

    return data


async def generate(
    qqid: Optional[int] = None,
    username: Optional[str] = None,
    all_perfect: bool = False,
    min_dx_star: Optional[int] = None,
    fitted: bool = False,
    all_perfect_plus: bool = False,
    achievement_mode: Optional[str] = None,
    difficulty_index: Optional[int] = None,
    all_songs: bool = False,
) -> Union[MessageSegment, str]:
    """
    生成b50
    
    Params:
        `qqid`: QQ号
        `username`: 用户名
        `all_perfect`: 是否为 ap50
        `min_dx_star`: DX SCORE 最低星级（1～5）
        `fitted`: 是否用谱面拟合定数重算 B50
        `all_perfect_plus`: 是否只保留玩家实际 AP+ 成绩
        `achievement_mode`: 达成率筛选模式
        `difficulty_index`: 谱面难度索引（0～4）
        `all_songs`: 是否忽略新旧曲分类并选取 Rating 最高的 50 项
    Returns:
        `Union[MessageSegment, str]`
    """
    from .maimaidx_lxns import LxnsError
    from .maimaidx_source import get_best50, get_service
    try:
        from .maimaidx_user import Theme, userstore

        if username:
            qqid = None
            theme = Theme.PRISM_PLUS
        else:
            theme = userstore.get(qqid).theme if qqid else Theme.PRISM_PLUS
        player, best50 = await get_best50(
            qqid=qqid,
            username=username,
            all_perfect=all_perfect,
            min_dx_star=min_dx_star,
            fitted=fitted,
            all_perfect_plus=all_perfect_plus,
            achievement_mode=achievement_mode,
            difficulty_index=difficulty_index,
            all_songs=all_songs,
        )
        service = get_service(qqid, username)
        draw_best = DrawBest.from_best50(
            player,
            best50,
            qqid=qqid,
            theme=theme,
            all_perfect=all_perfect,
            min_dx_star=min_dx_star,
            fitted=fitted,
            all_perfect_plus=all_perfect_plus,
            achievement_mode=achievement_mode,
            difficulty_index=difficulty_index,
            all_songs=all_songs,
            service=service,
        )

        msg = MessageSegment.image(image_to_base64(await draw_best.draw()))
    except (
        UserNotFoundError,
        UserNotExistsError,
        UserDisabledQueryError,
        TokenError,
        TokenDisableError,
        TokenNotFoundError,
        LxnsError,
    ) as e:
        msg = str(e)
    except Exception as e:
        log.error(traceback.format_exc())
        msg = f'未知错误：{type(e)}\n请联系Bot管理员'
    return msg
