def themed_path(theme: Theme, name: str) -> Path:
    """按主题返回素材路径，主题目录不存在时回退到 mai/pic 根目录。"""
    path = maimaidir / theme.value / name
    if path.exists():
        return path
    return maimaidir / name


def rating_asset_name(rating: int, theme: Theme = Theme.PRISM_PLUS) -> str:
    """按 DX Rating 返回与 B50 页头一致的 Rating 牌素材名。"""
    if rating < 1000:
        num = '01'
    elif rating < 2000:
        num = '02'
    elif rating < 4000:
        num = '03'
    elif rating < 7000:
        num = '04'
    elif rating < 10000:
        num = '05'
    elif rating < 12000:
        num = '06'
    elif rating < 13000:
        num = '07'
    elif rating < 14000:
        num = '08'
    elif rating < 14500:
        num = '09'
    elif rating < 15000:
        num = '10'
    elif theme == Theme.CIRCLE and rating >= 16000:
        num = '12'
    else:
        num = '11'
    return f'UI_CMN_DXRating_{num}.png'


def rating_star_asset_name(rating: int) -> str:
    """返回 Circle 主题 14000 以上 Rating 牌右侧的星标素材名。"""
    from bisect import bisect_right

    thresholds = [
        14000, 14250, 14500, 14750, 15000, 15250,
        15500, 15750, 16000, 16250, 16500, 16750,
    ]
    num_map = [1, 2, 1, 2, 1, 2, 3, 4, 1, 2, 3, 4]
    idx = max(bisect_right(thresholds, rating) - 1, 0)
    return f'UI_CMN_DXRating_Star_0{num_map[idx]}.png'


def dani_plate_asset_name(course_rank: int) -> str:
    """按玩家段位返回与 B50 页头一致的段位牌素材名。"""
    num = course_rank if course_rank <= 10 else course_rank + 1
    return f'UI_DNM_DaniPlate_{num:02d}.png'


def collection_asset_name(asset_type: str, collection_id: int) -> str:
    """返回落雪收藏头像/姓名框对应的素材文件名。"""
    return f'UI_{asset_type.capitalize()}_{collection_id:06d}.png'


def trophy_asset_name(color: Optional[str]) -> str:
    """将称号颜色映射到本地素材，未知颜色回退彩虹称号框。"""
    valid_colors = {'Normal', 'Bronze', 'Silver', 'Gold', 'Rainbow'}
    normalized = str(color or 'Rainbow').capitalize()
    if normalized not in valid_colors:
        normalized = 'Rainbow'
    return f'UI_CMN_Shougou_{normalized}.png'


