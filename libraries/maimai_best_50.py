    async def _collection_asset(
        self,
        asset_type: str,
        collection: Optional[Collection],
    ) -> Optional[Union[BytesIO, Path]]:
        if collection is None:
            return None
        file_name = collection_asset_name(asset_type, collection.id)
        local_path = mai_dir / asset_type / file_name
        if local_path.exists():
            return local_path
        if not maiApi.config.assets_online:
            return None

        content = await maiApi.online_asset(asset_type, file_name)
        if not content:
            return None
        try:
            local_path.parent.mkdir(parents=True, exist_ok=True)
            local_path.write_bytes(content)
            return local_path
        except OSError:
            return BytesIO(content)

